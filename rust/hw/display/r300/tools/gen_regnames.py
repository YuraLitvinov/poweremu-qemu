#!/usr/bin/env python3
"""Generate src/regnames.rs from hw/display/r300/r300_regnames.h."""
import re, sys, pathlib
here = pathlib.Path(__file__).resolve().parent.parent
hdr = here / "../r300/r300_regnames.h"
rows = re.findall(r'\{\s*(0x[0-9A-Fa-f]+),\s*"([A-Za-z0-9_]+)"\s*\}', hdr.read_text())
addrs = [int(a, 16) for a, _ in rows]
assert addrs == sorted(addrs) and len(set(addrs)) == len(addrs), "table must be sorted and unique"
out = ["//! R300 3D register names for traces.  Generated by tools/gen_regnames.py from",
       "//! hw/display/r300/r300_regnames.h (Mesa r300_reg.h, MIT license, Copyright 2000",
       "//! ATI Technologies Inc. and contributors); do not edit.", "",
       "use core::ffi::CStr;", "",
       "/// (address, name), sorted by address.",
       "pub static REG_NAMES: [(u16, &CStr); %d] = [" % len(rows)]
out += ['    (%s, c"%s"),' % (a, n) for a, n in rows]
out.append("];")
(here / "src/regnames.rs").write_text("\n".join(out) + "\n")
print(len(rows), "names")
