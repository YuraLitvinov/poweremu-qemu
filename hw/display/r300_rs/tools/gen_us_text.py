#!/usr/bin/env python3
"""Generate src/us_text.rs from the GLSL string blocks of r300_us.c.

The blocks are `static const char NAME[] = "..." "...";` (C comments between
the pieces are dropped).  Only the \\n escape occurs in them.
"""
import pathlib, re, sys

here = pathlib.Path(__file__).resolve().parent.parent
src = (here / "../r300/r300_us.c").read_text()
names = ["us_prelude_vs", "us_prelude_common", "us_prelude", "us_raw_tex", "us_raw_ssbo",
         "us_prelude2", "us_prelude_z"]

def literal_text(body):
    out, i = [], 0
    while i < len(body):
        c = body[i]
        if body.startswith("/*", i):
            i = body.index("*/", i) + 2
        elif body.startswith("//", i):
            i = body.index("\n", i) + 1
        elif c == '"':
            j = i + 1
            while body[j] != '"':
                if body[j] == "\\":
                    esc = body[j + 1]
                    assert esc in 'n"\\', "unhandled escape \\" + esc
                    out.append({"n": "\n", '"': '"', "\\": "\\"}[esc])
                    j += 2
                else:
                    out.append(body[j])
                    j += 1
            i = j + 1
        elif c.isspace():
            i += 1
        else:
            raise SystemExit("unexpected %r in a string block" % c)
    return "".join(out)

def rust_const(name, text):
    # A raw string keeps every byte, including indentation, as it is.
    assert '"####' not in text
    return 'pub const %s: &str = r####"%s"####;\n' % (name.upper(), text)

out = ["//! GLSL text blocks of the fragment-shader translator.  Generated by",
       "//! tools/gen_us_text.py from hw/display/r300/r300_us.c; do not edit.", ""]
for name in names:
    m = re.search(r"static const char %s\[\] =" % name, src)
    assert m, name
    # the block ends at the first ';' that is outside a string literal or comment
    i, n = m.end(), len(src)
    while True:
        if src.startswith("/*", i):
            i = src.index("*/", i) + 2
        elif src[i] == '"':
            i += 1
            while src[i] != '"':
                i += 2 if src[i] == "\\" else 1
            i += 1
        elif src[i] == ";":
            break
        else:
            i += 1
    out.append(rust_const(name, literal_text(src[m.end():i])))
(here / "src/us_text.rs").write_text("\n".join(out))
print("wrote", len(names), "blocks")
